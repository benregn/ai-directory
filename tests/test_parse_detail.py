# ---------------------------------------------------------------------------
# structured fallback for unexpected markup (synthetic — the live site is
# uniform, so real fixtures never exercise this path)
# ---------------------------------------------------------------------------

SYNTHETIC = """
<html><body><article class="listing">
<header class="listing-header"><div class="listing-identity"><h1>X</h1></div></header>
<section id="overview" class="listing-section"><div class="listing-prose"><p>text</p></div></section>
<section id="details" class="listing-section"><dl class="listing-details">
<div><dt>License</dt><dd>MIT</dd></div>
<div><dt>Quantum rating</dt><dd>seven</dd></div>
</dl></section>
<section id="changelog" class="listing-section"><h2>Changelog</h2><p>v2 shipped</p></section>
<aside class="promo">unrelated element</aside>
</article></body></html>
"""


def test_unknown_markup_is_retained_in_fallback():
    rec = parse_listing(SYNTHETIC, "https://githits.com/software-factories/x/")
    # unknown section retained with heading, text and raw html
    unknown = [f for f in rec["fallback"] if f["type"] == "unknown-section"]
    assert len(unknown) == 1
    assert unknown[0]["id"] == "changelog"
    assert unknown[0]["heading"] == "Changelog"
    assert "v2 shipped" in unknown[0]["text"]
    assert "<section" in unknown[0]["html"]
    # unexpected direct child retained too
    unexpected = [f for f in rec["fallback"] if f["type"] == "unexpected-element"]
    assert len(unexpected) == 1
    assert unexpected[0]["tag"] == "aside"
    # unrecognized detail label kept in place and flagged, not dropped
    labels = {e["label"]: e for e in rec["sections"]["details"]["entries"]}
    assert labels["Quantum rating"]["text"] == "seven"
    assert labels["Quantum rating"]["unrecognized_label"] is True
    assert labels["License"]["text"] == "MIT"
    assert "unrecognized_label" not in labels["License"]
