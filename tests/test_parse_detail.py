"""Extraction fidelity tests against saved real HTML.

Every expected value below was checked by hand against the source HTML in
tests/fixtures — none of it is generated by the parser under test.
"""

import json
from pathlib import Path

import pytest

from githits_directory.parse import ListingParseError, parse_listing

FIXTURES = Path(__file__).parent / "fixtures"


def load(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


@pytest.fixture(scope="module")
def aeon():
    return parse_listing(load("detail/aeon.html"), "https://githits.com/software-factories/aeon/")


@pytest.fixture(scope="module")
def x8090():
    return parse_listing(load("detail/8090.html"), "https://githits.com/software-factories/8090/")


def detail_entries(rec):
    return {e["label"]: e for e in rec["sections"]["details"]["entries"]}


